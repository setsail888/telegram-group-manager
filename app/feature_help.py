class FeatureHelp:
    def __init__(self, bot):
        self.bot = bot

    def add_admin(self, keyboard, cid, page):
        if page not in ADMIN_PAGES:
            return
        data = f"fh:{cid}:{page}"
        if not any(b.get("callback_data") == data for row in keyboard for b in row):
            keyboard.append([self.bot._button(_ui("📖 功能说明"), data)])

    def add_member(self, keyboard, cid, page):
        if page in MEMBER_PAGES:
            keyboard.append([self.bot._button(_ui("📖 功能说明"), f"pc:{cid}:help:{page}")])

    def _show(self, uid, cid, topic, mid, back, links=()):
        template, document = GUIDES[topic]
        values = dict(self.bot.store.settings(cid)) if cid is not None else {}
        if values:
            values.update(mention_trigger=values["mention_limit"]+1,
                          flood_trigger=values["flood_limit"]+1,
                          media_trigger=values["media_flood_limit"]+1)
        text = template.format(**values)
        keyboard = [[self.bot._button(label, data) for label, data in row] for row in links]
        keyboard += [[{"text": _ui("🌐 在线详细文档"), "url": DOCS_URL+quote(document, safe="/#")}],
                     [self.bot._button(_ui("⬅️ 返回本功能"), back)]]
        return self.bot._edit_or_send(uid, mid, text, keyboard)

    def admin(self, uid, cid, page, mid):
        if page not in ADMIN_PAGES:
            raise ValueError(_ui("未知功能说明，请重新打开功能页。"))
        back = (f"wl:{cid}:0" if page == "wordlist" else
                f"ad:{cid}:orders:0" if page == "orders" else
                f"v:{cid}:words" if page == "wordexport" else f"v:{cid}:{page}")
        return self._show(uid, cid, ADMIN_PAGES[page], mid, back)

    def member(self, uid, cid, page, mid):
        if page not in MEMBER_PAGES:
            raise ValueError(_ui("未知功能说明，请重新打开功能页。"))
        topic, target = MEMBER_PAGES[page]
        links = ()
        if page == "home":
            # Read individual guides before pressing action buttons such as check-in.
            links = (
                ((_ui("🪙 积分签到"), f"pc:{cid}:help:balance"),
                 (_ui("🎁 积分商城"), f"pc:{cid}:help:shop")),
                ((_ui("🎉 免费抽奖"), f"pc:{cid}:help:raffle"),
                 (_ui("📖 群规"), f"pc:{cid}:help:rules")),
                ((_ui("🆔 我的ID"), f"pc:{cid}:help:id"),),
            )
        return self._show(uid, cid, topic, mid, f"pc:{cid}:{target}:0", links)

    def language(self, uid, owner, mid, *, back=None):
        back = back or (f"lang:group:{owner}" if owner < 0 else "lang:self")
        return self._show(uid, owner if owner < 0 else None, "language", mid, back)
